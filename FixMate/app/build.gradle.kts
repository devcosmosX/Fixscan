// Load the Claude API key from local.properties (git-ignored) or the environment.
// The key is injected into BuildConfig at build time — it is never hardcoded in source
// and never committed to version control.
val claudeApiKey: String = run {
    val props = Properties()
    val localFile = rootProject.file("local.properties")
    if (localFile.exists()) {
        FileInputStream(localFile).use { props.load(it) }
    }
    (props.getProperty("CLAUDE_API_KEY") ?: System.getenv("CLAUDE_API_KEY") ?: "").trim()
}

